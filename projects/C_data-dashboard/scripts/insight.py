"""분석 결과를 사람이 읽는 인사이트 문장으로 바꾼다.

숫자를 그대로 옮기는 것이 아니라 "그래서 무엇을 하라"까지 쓴다.
Claude 에게 그대로 넘길 프롬프트도 여기서 만든다.
"""
import json
import sys

PROMPT = """이 매출 데이터 분석 결과를 보고 경영진에게 보고할 인사이트를 작성해줘.

{facts}

포함해야 할 것:
1. 가장 중요한 발견 3가지
2. 각 발견의 비즈니스 의미
3. 당장 실행할 수 있는 액션 3가지
4. 주의해야 할 점
비전문가도 이해할 수 있는 언어로, 숫자는 반드시 근거와 함께 써줘."""


def josa(word):
    """받침이 있으면 "이", 없으면 "가". 제품명이 숫자로 끝나는 경우까지 본다."""
    digit = {'0': True, '1': True, '3': True, '6': True, '7': True, '8': True,
             '2': False, '4': False, '5': False, '9': False}
    ch = word.strip()[-1]
    if ch.isdigit():
        return '이' if digit[ch] else '가'
    if '가' <= ch <= '힣':
        return '이' if (ord(ch) - 0xAC00) % 28 else '가'
    return '이'


def facts(r):
    b, t = r['기본'], r['트렌드']
    cat = list(r['카테고리'].items())
    reg = list(r['지역'].items())
    pro = list(r['제품'].items())
    return '\n'.join([
        f'- 기간: 2025년 1~12월, 거래 {b["건수"]:,}건',
        f'- 총 매출 {b["총매출"]:,}원, 월 평균 {b["월평균"]:,}원, '
        f'건당 평균 {b["건당평균"]:,}원',
        f'- 최고 {t["최고월"]}월 {t["최고월매출"]:,}원 / '
        f'최저 {t["최저월"]}월 {t["최저월매출"]:,}원',
        f'- 상반기 {t["상반기"]:,}원 → 하반기 {t["하반기"]:,}원 '
        f'({t["하반기증가율"]:+.1f}%)',
        f'- 카테고리 1위 {cat[0][0]} {cat[0][1]:,}원, '
        f'최하위 {cat[-1][0]} {cat[-1][1]:,}원',
        f'- 지역 1위 {reg[0][0]} {reg[0][1]:,}원, 최하위 {reg[-1][0]} {reg[-1][1]:,}원',
        f'- 제품 1위 {pro[0][0]} {pro[0][1]:,}원',
        f'- 매출액과 마케팅비용의 상관계수 {r["상관관계"]["매출액-마케팅비용"]}',
        f'- 상위 이상치 {r["이상치"]["건수"]}건이 전체 매출의 {r["이상치"]["비중"]}%',
    ])


def report(r):
    b, t = r['기본'], r['트렌드']
    cat = list(r['카테고리'].items())
    reg = list(r['지역'].items())
    pro = list(r['제품'].items())
    tot = b['총매출']
    corr = r['상관관계']['매출액-마케팅비용']
    top3 = sum(v for _, v in reg[:3]) / tot * 100

    return '\n'.join([
        'AI 인사이트 리포트', '',
        '핵심 발견', '',
        '1. 하반기에 매출이 몰린다',
        f'   상반기 {t["상반기"] / 1e8:.1f}억 원에서 하반기 {t["하반기"] / 1e8:.1f}억 원으로'
        f' {t["하반기증가율"]:.0f}% 늘었습니다. 특히 {t["최고월"]}월 한 달이'
        f' {t["최고월매출"] / 1e8:.2f}억 원으로 최저인 {t["최저월"]}월의'
        f' {t["최고월매출"] / t["최저월매출"]:.1f}배입니다.',
        '   → 연말 수요가 실적을 좌우합니다. 재고와 인력을 10월부터 미리 배치해야 합니다.',
        '',
        '2. 마케팅비가 매출을 따라 움직인다',
        f'   매출액과 마케팅비용의 상관계수가 {corr}입니다. 강한 양의 관계지만'
        f' 인과는 아닙니다. 많이 팔린 달에 더 썼을 수도 있습니다.',
        '   → 한 카테고리에서 예산만 늘려 보는 소규모 실험으로 인과를 확인하세요.',
        '',
        '3. 매출이 소수 거래에 쏠려 있다',
        f'   상위 {r["이상치"]["건수"]}건, 전체 거래의'
        f' {r["이상치"]["건수"] / b["건수"] * 100:.1f}%가'
        f' 매출의 {r["이상치"]["비중"]}%를 만듭니다.',
        '   → 이 거래들의 공통점(제품·지역·시기)을 따로 보면 재현할 방법이 보입니다.',
        '',
        '구성', '',
        f'- 카테고리: {cat[0][0]}가 {cat[0][1] / tot * 100:.1f}%로 1위,'
        f' {cat[-1][0]}가 {cat[-1][1] / tot * 100:.1f}%로 최하위',
        f'- 지역: 상위 3개({reg[0][0]}·{reg[1][0]}·{reg[2][0]})가 {top3:.1f}%',
        f'- 제품: {pro[0][0]}{josa(pro[0][0])} 단일 제품 1위'
        f' ({pro[0][1] / tot * 100:.1f}%)',
        '',
        '추천 액션', '',
        '1. 10~12월 프로모션 예산을 앞당겨 편성합니다.',
        f'2. {reg[-1][0]}·{reg[-2][0]} 지역의 부진 원인을 채널별로 나눠 봅니다.',
        f'3. {cat[-1][0]} 카테고리는 유지할지 접을지 다음 분기에 결정합니다.',
        '',
        '주의', '',
        '- 상관관계는 인과관계가 아닙니다.',
        '- 결측치를 중앙값·최빈값으로 채웠습니다. 원본에 빈 칸이 있었다는 사실을'
        ' 보고서에 함께 적으세요.',
        '- 1년 치 데이터라 계절성을 한 번밖에 관찰하지 못했습니다.',
    ])


if __name__ == '__main__':
    r = json.load(open('output/analysis.json', encoding='utf-8'))
    if len(sys.argv) > 1 and sys.argv[1] == '--prompt':
        print(PROMPT.format(facts=facts(r)))
    else:
        text = report(r)
        print(text)
        open('output/insight.md', 'w', encoding='utf-8').write(text + '\n')
